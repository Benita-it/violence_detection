from fastapi import APIRouter
from pydantic import BaseModel
from email.message import EmailMessage
from pathlib import Path
from dotenv import load_dotenv
import aiosmtplib
import os
import base64

PROJECT_ROOT = Path(__file__).resolve().parents[3]
load_dotenv(PROJECT_ROOT / ".env")

router = APIRouter(prefix="/api", tags=["Alert"])

class AlertRequest(BaseModel):
    prediction: str
    confidence: float
    date: str
    time: str
    location: str
    address: str
    latitude: float | None = None
    longitude: float | None = None
    evidence_image: str | None = None

@router.post("/send-alert")
async def send_alert(alert: AlertRequest):
    print("\n========== VIOLENCE ALERT ==========")
    print(f"Prediction  : {alert.prediction}")
    print(f"Confidence  : {alert.confidence}%")
    print(f"Date        : {alert.date}")
    print(f"Time        : {alert.time}")
    print(f"Location    : {alert.location}")
    print(f"Address     : {alert.address}")
    print(f"Latitude    : {alert.latitude}")
    print(f"Longitude   : {alert.longitude}")
    print("====================================\n")

    sender_email = os.getenv("SMTP_EMAIL")
    app_password = os.getenv("SMTP_APP_PASSWORD")
    caretaker_email = os.getenv("CARETAKER_EMAIL")

    if not sender_email or not app_password or not caretaker_email:
        print("❌ Email configuration missing in .env")
        print(f"   SMTP_EMAIL configured: {bool(sender_email)}")
        print(f"   SMTP_APP_PASSWORD configured: {bool(app_password)}")
        print(f"   CARETAKER_EMAIL configured: {bool(caretaker_email)}")
        return {"success": False, "message": "Email configuration is missing in .env"}

    try:
        message = EmailMessage()
        message["From"] = sender_email
        message["To"] = caretaker_email
        message["Subject"] = "🚨 Violence Detected Alert"

        body = f"""
🚨 VIOLENCE DETECTED ALERT

A possible violence incident has been detected by the AI Violence Detection System.

----------------------------------------
ALERT DETAILS
----------------------------------------

Prediction  : {alert.prediction}
Confidence  : {alert.confidence}%

Date        : {alert.date}
Time        : {alert.time}

GPS Location:
{alert.location}

Latitude:
{alert.latitude}

Longitude:
{alert.longitude}

Google Maps Location:
{alert.address}

----------------------------------------

Please check the situation immediately.

This alert was automatically generated by the AI Violence Detection System.
"""
        message.set_content(body)

        evidence_attached = False

        if alert.evidence_image:
            try:
                image_data = alert.evidence_image
                if "," in image_data:
                    image_data = image_data.split(",", 1)[1]

                image_bytes = base64.b64decode(image_data)

                message.add_attachment(
                    image_bytes,
                    maintype="image",
                    subtype="jpeg",
                    filename="violence_evidence.jpg"
                )

                evidence_attached = True
                print("📸 Evidence image attached successfully")
            except Exception as image_error:
                print("⚠️ Evidence image attachment failed:", image_error)
        else:
            print("⚠️ No evidence image received")

        print("📧 Sending email to caretaker...")

        await aiosmtplib.send(
            message,
            hostname="smtp.gmail.com",
            port=587,
            start_tls=True,
            username=sender_email,
            password=app_password
        )

        print("✅ Email sent successfully to caretaker")

        return {
            "success": True,
            "message": "Violence alert email sent successfully",
            "alert": {
                "prediction": alert.prediction,
                "confidence": alert.confidence,
                "date": alert.date,
                "time": alert.time,
                "location": alert.location,
                "address": alert.address,
                "latitude": alert.latitude,
                "longitude": alert.longitude,
                "evidence_attached": evidence_attached
            }
        }

    except Exception as error:
        print("❌ Email sending failed:", error)
        return {
            "success": False,
            "message": "Failed to send violence alert email",
            "error": str(error)
        }
